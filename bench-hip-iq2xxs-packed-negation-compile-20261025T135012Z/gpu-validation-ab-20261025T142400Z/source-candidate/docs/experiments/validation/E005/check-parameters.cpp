int main() {
  int checked=0;
  for(int type=0;type<GGML_TYPE_COUNT;++type) for(int cols=1;cols<=8;++cols)
  for(bool small:{false,true}) for(bool halve:{false,true}) {
    const auto t=static_cast<ggml_type>(type);
    const int a=before::calc_nwarps(t,cols,before::MMVQ_PARAMETERS_RDNA3_0,small,halve);
    const int b=after::calc_nwarps(t,cols,after::MMVQ_PARAMETERS_GFX1101,small,halve);
    if(a!=b) return 1;
    const int rows=before::calc_rows_per_block(t,cols,before::MMVQ_PARAMETERS_RDNA3_0,small,a);
    const int expected=type==GGML_TYPE_IQ3_XXS && cols==1 ? 2 : rows;
    if(after::calc_rows_per_block(t,cols,after::MMVQ_PARAMETERS_GFX1101,small,b)!=expected) return 2;
    ++checked;
  }
  for(int rows:{1,63,64,65,5120,17408}) {
    int seen=0;
    for(int block=0;block<(rows+1)/2;++block) for(int i=0;i<2;++i) {
      const int row=2*block+i;
      if(row>=rows) continue;
      if(row!=seen++) return 3;
    }
    if(seen!=rows) return 4;
  }
  std::printf("PASS: %d configurations; warp counts unchanged; only IQ3_XXS decode changes to two rows; tail coverage correct\n",checked);
}
